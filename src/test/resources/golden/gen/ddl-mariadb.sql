CREATE TABLE HR.TB_EMP_HIST (
    EMP_NO INT NOT NULL COMMENT '사원 번호',
    START_DATE DATETIME NOT NULL COMMENT '시작일',
    JOB_ID VARCHAR(10) NOT NULL COMMENT '직무',
    DEPT_NM VARCHAR(30),
    SALARY DECIMAL(8,2) COMMENT '급여',
    CLASS VARCHAR(5) COMMENT '등급',
